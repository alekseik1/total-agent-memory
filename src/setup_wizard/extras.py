"""Claude Code hooks and agent skills for every installer. They ship with the git checkout, not with the wheel.

Hook scripts are copied to ~/.claude/hooks and registered in ~/.claude/settings.json. Existing scripts are kept
unless ``overwrite`` is set, and hook entries are only ever added, so user hooks survive re-installs. The shared
runtime in ~/.claude/hooks/lib (common.sh, common.ps1, tam_hook.py, ...) is always refreshed because every script,
old or new, needs the current helper; ``install-env.{sh,ps1}`` is regenerated there so the copies find the
checkout's src/ and the memory directory.
"""
import json
import re
import shlex
import shutil
from dataclasses import dataclass
from pathlib import Path

from setup_wizard.clients import ConfigError, Host, proxy_entry, read_json, server_entry
from setup_wizard.files import atomic_write

EXECUTABLE_MODE = 0o755
SKILLS = ("memory-protocol", "onboard", "onboard-report", "report")
ONBOARDING = ("onboard", "onboard-report")
AGENT_SKILLS = (*ONBOARDING, "report")
POWERSHELL = 'powershell -ExecutionPolicy Bypass -NoProfile -File "{path}"'
# Tools whose calls the action log and the nudge counters use; Read/Grep/Glob/LS/Todo* are dropped by
# src/ambient/actions.py anyway, so spawning Python for them only costs about 130 ms per call.
POST_TOOL_USE_MATCHER = "Edit|Write|MultiEdit|NotebookEdit|Bash"
# PreToolUse for the memory server's own tools: adds `_ctx` (agent, session, workspace) to the tool input.
PROVENANCE_MATCHER = "mcp__memory__.*"
# Written next to settings.json by every hook install: the registration of the "memory" server the installer
# saw. The provenance hook injects `_ctx` only while the effective "memory" server still has this registration,
# so a third-party server that happens to be named "memory" never receives it.
PROVENANCE_MARKER = "tam-provenance.json"
PROVENANCE_SERVER = "memory"
FINGERPRINT_KEYS = ("command", "args", "url")
HOOK_GROUPS: tuple[tuple[str, str, tuple[str, ...]], ...] = (
    ("SessionStart", "", ("session-start",)),
    ("SessionEnd", "", ("session-end",)),
    ("Stop", "", ("on-stop",)),
    ("UserPromptSubmit", "", ("user-prompt-submit",)),
    ("PreToolUse", "Write|Edit", ("pre-edit",)),
    ("PreToolUse", "Bash|Edit|Write|MultiEdit|NotebookEdit", ("rule-reminder",)),
    ("PreToolUse", PROVENANCE_MATCHER, ("inject-provenance",)),
    ("PostToolUse", "Bash", ("memory-trigger", "on-bash-error")),
    # Claude Code reports a failed Bash call through PostToolUseFailure, not PostToolUse.
    ("PostToolUseFailure", "Bash", ("memory-trigger", "on-bash-error")),
    ("PostToolUse", "Write|Edit", ("auto-capture",)),
    ("PostToolUse", POST_TOOL_USE_MATCHER, ("post-tool-use",)),
    # Failed calls of the same tools go to the agent action log too.
    ("PostToolUseFailure", POST_TOOL_USE_MATCHER, ("post-tool-use",)),
)

PLUGIN_NAME = "total-agent-memory"

LIB_DIR = "lib"
INSTALL_ENV = "install-env"
LIB_SHARED_PATTERNS = ("*.py",)


def _suffix(host: Host) -> str:
    return ".ps1" if host.system == "Windows" else ".sh"


def _sh_double_quoted(value: str) -> str:
    for char in ("\\", '"', "$", "`"):
        value = value.replace(char, "\\" + char)
    return value


HOOKS_VERSION_VAR = "TAM_HOOKS_VERSION"
_VERSION_LINE = re.compile(r'^VERSION\s*=\s*"([^"]+)"', re.MULTILINE)


def checkout_version(root: Path) -> str:
    """VERSION of the checkout's src/version.py, '' when unreadable."""
    try:
        match = _VERSION_LINE.search(Path(root, "src", "version.py").read_text(encoding="utf-8"))
    except OSError:
        return ""
    return match.group(1) if match else ""


def install_env_text(host: Host, root: Path, memory_dir: Path | None) -> str:
    """Defaults the copied hooks load before resolving paths; variables already set in the environment win."""
    values = {"CLAUDE_MEMORY_INSTALL_DIR": str(root)}
    if checkout_version(root):
        # Stamp: the hooks warn when the checkout they point at is a different release.
        values[HOOKS_VERSION_VAR] = checkout_version(root)
    if memory_dir is not None:
        values["TAM_MEMORY_DIR"] = str(memory_dir)
    lines = ["# Generated by the TAM installer on every hook install; local edits are overwritten."]
    if host.system == "Windows":
        lines += [f"if (-not $env:{name}) {{ $env:{name} = '{value.replace(chr(39), chr(39) * 2)}' }}"
                  for name, value in values.items()]
    else:
        lines += [f': "${{{name}:={_sh_double_quoted(value)}}}"' for name, value in values.items()]
    return "\n".join(lines) + "\n"


def hooks_available(root: Path, host: Host) -> bool:
    return (root / "hooks" / ("session-start" + _suffix(host))).is_file()


def skills_available(root: Path) -> bool:
    return (root / "skills" / "memory-protocol" / "SKILL.md").is_file()


def _command(host: Host, script: Path) -> str:
    # Hooks run through a shell, so a home path with spaces must stay one word.
    return POWERSHELL.format(path=script) if host.system == "Windows" else shlex.quote(str(script))


@dataclass(frozen=True)
class HookPlan:
    scripts: tuple[tuple[Path, Path], ...]
    settings: Path
    text: str
    added: tuple[str, ...]
    overwrite: bool
    runtime: tuple[tuple[Path, Path], ...] = ()
    generated: tuple[tuple[Path, str], ...] = ()
    plugin_active: bool = False


def _settings(path: Path) -> dict:
    data = read_json(path)
    hooks = data.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise ConfigError(f"{path}: 'hooks' must be an object")
    return data


def plugin_hooks_active(settings: dict) -> bool:
    """True when the total-agent-memory plugin is enabled: its hooks.json already runs every hook."""
    enabled = settings.get("enabledPlugins")
    return isinstance(enabled, dict) and any(
        bool(value) and str(key).split("@", 1)[0] == PLUGIN_NAME for key, value in enabled.items())


def plan_hooks(root: Path, host: Host, overwrite: bool = False, memory_dir: Path | None = None) -> HookPlan:
    target = host.home / ".claude" / "hooks"
    suffix = _suffix(host)
    scripts = tuple((source, target / source.name) for source in sorted((root / "hooks").glob("*" + suffix)))
    lib = root / "hooks" / LIB_DIR
    runtime = tuple((source, target / LIB_DIR / source.name)
                    for pattern in ("*" + suffix, *LIB_SHARED_PATTERNS)
                    for source in sorted(lib.glob(pattern)) if source.stem != INSTALL_ENV)
    generated = ((target / LIB_DIR / (INSTALL_ENV + suffix), install_env_text(host, root, memory_dir)),) \
        if runtime else ()
    settings = host.home / ".claude" / "settings.json"
    data = _settings(settings)
    added = []
    plugin_active = plugin_hooks_active(data)
    # With the plugin enabled, settings.json entries would run every event twice (doubled action log rows,
    # nudges and auto-saves); the scripts and the runtime are still installed for Codex and manual use.
    for event, matcher, names in () if plugin_active else HOOK_GROUPS:
        entries = data["hooks"].setdefault(event, [])
        if not isinstance(entries, list):
            raise ConfigError(f"{settings}: hooks.{event} must be a list")
        present = {hook.get("command") for block in entries if isinstance(block, dict)
                   for hook in block.get("hooks", []) if isinstance(hook, dict)}
        missing = [_command(host, target / (name + suffix)) for name in names
                   if (root / "hooks" / (name + suffix)).is_file()]
        missing = [command for command in missing if command not in present]
        if missing:
            entries.append({"matcher": matcher, "hooks": [{"type": "command", "command": c} for c in missing]})
            added.append(event)
    return HookPlan(scripts, settings, json.dumps(data, indent=2, ensure_ascii=False) + "\n", tuple(added), overwrite,
                    runtime, generated, plugin_active)


def provenance_fingerprint(entry: object) -> dict | None:
    """The launch identity of a registered MCP server (command+args or url; env and headers hold secrets)."""
    if not isinstance(entry, dict):
        return None
    fingerprint = {key: entry[key] for key in FINGERPRINT_KEYS if entry.get(key)}
    return fingerprint or None


def installer_registered(entry: object, url: str | None = None) -> bool:
    """True when ``entry`` is a registration the installer itself writes: its stdio launch (console script, src/server.py
    or the daemon proxy) or, when the caller knows it, the HTTP endpoint it just registered."""
    fingerprint = provenance_fingerprint(entry)
    if fingerprint is None:
        return False
    if url is not None:
        return fingerprint.get("url") == url
    launches = [server_entry({}), proxy_entry({})]
    return any(fingerprint == provenance_fingerprint({"command": launch.command, "args": list(launch.args)})
               for launch in launches)


def write_provenance_marker(claude_dir: Path, url: str | None = None) -> Path:
    """Record the TAM registration for the provenance hook, or clear the marker. Only a server the installer itself
    registered is recorded (``url`` for an HTTP install). A "memory" entry the user pointed elsewhere is never
    recorded; a marker written earlier is kept only while the entry still matches it (installs that do not know
    the endpoint, such as update.sh, must not drop an HTTP install's marker)."""
    marker = claude_dir / PROVENANCE_MARKER
    servers = read_json(claude_dir.parent / ".claude.json").get("mcpServers")
    entry = servers.get(PROVENANCE_SERVER) if isinstance(servers, dict) else None
    fingerprint = provenance_fingerprint(entry)
    if fingerprint is not None and not installer_registered(entry, url):
        recorded = read_json(marker).get("servers")
        previous = recorded.get(PROVENANCE_SERVER) if isinstance(recorded, dict) else None
        fingerprint = fingerprint if url is None and previous == fingerprint else None
    if fingerprint is None:
        marker.unlink(missing_ok=True)
        return marker
    atomic_write(marker, json.dumps({"servers": {PROVENANCE_SERVER: fingerprint}}, indent=2) + "\n")
    return marker


def apply_hooks(hook_plan: HookPlan) -> tuple[int, int]:
    copied = skipped = 0
    for source, destination in hook_plan.scripts:
        if destination.exists() and not hook_plan.overwrite:
            skipped += 1
            continue
        text = source.read_text(encoding="utf-8")
        if destination.exists() and destination.read_text(encoding="utf-8") != text:
            # Same rule as refresh_installed_hooks: an overwritten script keeps its previous text as <name>.bak.
            atomic_write(destination.with_name(destination.name + BACKUP_SUFFIX),
                         destination.read_text(encoding="utf-8"), EXECUTABLE_MODE)
        atomic_write(destination, text, EXECUTABLE_MODE)
        copied += 1
    for source, destination in hook_plan.runtime:
        atomic_write(destination, source.read_text(encoding="utf-8"), EXECUTABLE_MODE)
        copied += 1
    for destination, text in hook_plan.generated:
        atomic_write(destination, text)
    atomic_write(hook_plan.settings, hook_plan.text)
    write_provenance_marker(hook_plan.settings.parent)
    return copied, skipped


BACKUP_SUFFIX = ".bak"


def refresh_installed_hooks(root: Path, host: Host, memory_dir: Path | None = None) -> list[Path]:
    """Bring hook copies already installed in ~/.claude/hooks up to the checkout; settings.json is not touched.

    Used by update.sh: ``git pull`` changes src/ and hooks/ but the copies keep running the old
    ``lib/tam_hook.py`` against the new ``src/``. The runtime in lib/ is always rewritten; a top-level script
    is rewritten only when it exists and differs, after saving the previous text as ``<name>.bak``.
    Returns the files written; an install without wizard hooks yields [].
    """
    hook_plan = plan_hooks(root, host, memory_dir=memory_dir)
    if not (host.home / ".claude" / "hooks" / LIB_DIR).is_dir():
        return []
    written: list[Path] = []
    for source, destination in hook_plan.scripts:
        text = source.read_text(encoding="utf-8")
        if not destination.exists() or destination.read_text(encoding="utf-8") == text:
            continue
        atomic_write(destination.with_name(destination.name + BACKUP_SUFFIX),
                     destination.read_text(encoding="utf-8"), EXECUTABLE_MODE)
        atomic_write(destination, text, EXECUTABLE_MODE)
        written.append(destination)
    for source, destination in hook_plan.runtime:
        atomic_write(destination, source.read_text(encoding="utf-8"), EXECUTABLE_MODE)
        written.append(destination)
    for destination, text in hook_plan.generated:
        atomic_write(destination, text)
        written.append(destination)
    written.append(write_provenance_marker(hook_plan.settings.parent))
    return written


def remove_hooks(host: Host) -> Path | None:
    """Drop the hook entries this module registers; the scripts stay in ~/.claude/hooks."""
    settings = host.home / ".claude" / "settings.json"
    if not settings.is_file():
        return None
    data = _settings(settings)
    target = host.home / ".claude" / "hooks"
    ours = {_command(host, target / (name + _suffix(host))) for _event, _matcher, names in HOOK_GROUPS for name in names}
    changed = False
    for event in list(data["hooks"]):
        blocks = data["hooks"][event]
        if not isinstance(blocks, list):
            continue
        for block in blocks:
            if isinstance(block, dict) and isinstance(block.get("hooks"), list):
                kept = [h for h in block["hooks"] if not (isinstance(h, dict) and h.get("command") in ours)]
                changed |= len(kept) != len(block["hooks"])
                block["hooks"] = kept
        data["hooks"][event] = [b for b in blocks if not (isinstance(b, dict) and b.get("hooks") == [])]
        if not data["hooks"][event]:
            del data["hooks"][event]
    if not changed:
        return None
    atomic_write(settings, json.dumps(data, indent=2, ensure_ascii=False) + "\n")
    return settings


def skill_copies(root: Path, host: Host, clients: list[str]) -> list[tuple[Path, Path]]:
    """(source, target) pairs; a source directory is copied as a tree, a file as a file."""
    skills = root / "skills"
    copies: list[tuple[Path, Path]] = []

    def tree(base: Path, names: tuple[str, ...]) -> None:
        copies.extend((skills / name, base / name) for name in names if (skills / name / "SKILL.md").is_file())

    if not skills_available(root):
        return copies
    if "claude-code" in clients:
        tree(host.home / ".claude" / "skills", SKILLS)
    if "codex" in clients:
        tree(host.codex_home() / "skills", SKILLS)
        tree(host.home / ".agents" / "skills", AGENT_SKILLS)
        if (root / "codex-skill" / "SKILL.md").is_file():
            copies.append((root / "codex-skill", host.home / ".agents" / "skills" / "memory"))
    if "opencode" in clients:
        tree(host.home / ".opencode" / "skills", SKILLS)
    if "continue" in clients:
        copies.append((skills / "memory-protocol" / "SKILL.md", host.home / ".continue" / "rules" / "memory-protocol.md"))
    return copies


def apply_skills(copies: list[tuple[Path, Path]]) -> list[Path]:
    for source, target in copies:
        if source.is_dir():
            shutil.copytree(source, target, dirs_exist_ok=True)
        else:
            atomic_write(target, source.read_text(encoding="utf-8"))
    return [target for _source, target in copies]
