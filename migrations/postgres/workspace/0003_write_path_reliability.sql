ALTER TABLE write_intents ADD COLUMN lease_until text;
CREATE INDEX idx_write_intents_pending ON write_intents(created_at) WHERE status = 'pending';

CREATE TABLE embedding_pending (
    knowledge_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempts bigint NOT NULL DEFAULT 0,
    last_error text,
    next_attempt_at text NOT NULL,
    status text NOT NULL DEFAULT 'pending',
    created_at text NOT NULL,
    updated_at text NOT NULL,
    CHECK (status IN ('pending', 'failed'))
);
CREATE INDEX idx_embedding_pending_due ON embedding_pending(status, next_attempt_at);

CREATE TABLE error_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts text NOT NULL,
    component text NOT NULL,
    message text NOT NULL,
    exc_type text NOT NULL,
    trace_head text,
    occurrences bigint NOT NULL DEFAULT 1
);
CREATE INDEX idx_error_log_ts ON error_log(ts);
CREATE INDEX idx_error_log_component_ts ON error_log(component, ts);

CREATE TABLE importance_budget_log (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_id bigint NOT NULL,
    project text NOT NULL,
    ktype text NOT NULL,
    requested text NOT NULL,
    applied text NOT NULL,
    budget bigint NOT NULL,
    used bigint NOT NULL,
    created_at text NOT NULL
);
CREATE INDEX idx_importance_budget_log_project ON importance_budget_log(project, created_at);
CREATE INDEX idx_importance_budget_log_knowledge ON importance_budget_log(knowledge_id);

