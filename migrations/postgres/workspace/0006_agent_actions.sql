-- PostgreSQL twin of migrations/040_agent_actions.sql (same mapping rules as
-- 0001_baseline.sql): the agent action log written by the client hooks,
-- rules.success_lower_bound, the 95% Wilson lower bound of the explicitly rated
-- success share, and the Stop-hook compliance counters auto_success_count /
-- auto_fail_count, kept apart from the explicit ratings. Existing rated rules
-- get their bound here; SQLite computes it at store start
-- (rule_surfaces.backfill_lower_bounds) because its SQL has no sqrt.

CREATE TABLE agent_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts text NOT NULL,
    client text NOT NULL DEFAULT 'claude-code',
    session_id text NOT NULL DEFAULT '',
    project text NOT NULL DEFAULT 'general',
    tool text NOT NULL,
    summary text NOT NULL DEFAULT '',
    status text NOT NULL DEFAULT 'ok' CHECK (status IN ('ok', 'failed', 'interrupted')),
    exit_code bigint
);
CREATE INDEX idx_agent_actions_session_ts ON agent_actions (session_id, ts);
CREATE INDEX idx_agent_actions_ts ON agent_actions (ts);
CREATE INDEX idx_agent_actions_project_ts ON agent_actions (project, ts);

ALTER TABLE rules ADD COLUMN success_lower_bound double precision DEFAULT 0.0;
ALTER TABLE rules ADD COLUMN auto_success_count bigint DEFAULT 0;
ALTER TABLE rules ADD COLUMN auto_fail_count bigint DEFAULT 0;

-- Wilson score interval, z = 1.959963984540054 (rule_surfaces.WILSON_Z_95).
UPDATE rules SET success_lower_bound = GREATEST(0.0,
    ((success_count::double precision / n) + z2 / (2 * n)
     - 1.959963984540054 * sqrt((success_count::double precision / n)
                                * (1 - success_count::double precision / n) / n + z2 / (4 * n * n)))
    / (1 + z2 / n))
FROM (SELECT id AS rid, (COALESCE(success_count, 0) + COALESCE(fail_count, 0))::double precision AS n,
             1.959963984540054 ^ 2 AS z2
      FROM rules) AS rated
WHERE rules.id = rated.rid AND rated.n > 0 AND COALESCE(rules.success_count, 0) > 0;

