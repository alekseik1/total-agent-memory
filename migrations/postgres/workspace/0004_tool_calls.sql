-- PostgreSQL twin of migrations/041_tool_calls.sql: per-tool MCP call telemetry.
-- Same columns in the same order, mapped by the baseline rules (INTEGER -> bigint,
-- REAL -> double precision, TEXT -> text, INTEGER PRIMARY KEY -> identity).
-- Sizes only, never argument or result contents.

CREATE TABLE tool_calls (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts text NOT NULL,
    tool text NOT NULL,
    duration_ms double precision NOT NULL,
    ok bigint NOT NULL CHECK (ok IN (0, 1)),
    error_class text,
    args_bytes bigint NOT NULL DEFAULT 0,
    result_bytes bigint NOT NULL DEFAULT 0,
    profile text NOT NULL DEFAULT 'full'
);
CREATE INDEX idx_tool_calls_ts ON tool_calls (ts);
CREATE INDEX idx_tool_calls_tool_ts ON tool_calls (tool, ts);

