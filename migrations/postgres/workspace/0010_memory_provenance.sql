-- PostgreSQL twin of migrations/046_memory_provenance.sql (same mapping rules as 0001_baseline.sql):
-- who wrote each memory. The trigger removes a record's rows when the record itself is deleted.

CREATE TABLE memory_provenance (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    knowledge_id bigint NOT NULL,
    tool text NOT NULL DEFAULT '',
    agent text NOT NULL DEFAULT '',
    session_id text NOT NULL DEFAULT '',
    workspace text NOT NULL DEFAULT '',
    repo text NOT NULL DEFAULT '',
    tool_use_id text NOT NULL DEFAULT '',
    turn_id text NOT NULL DEFAULT '',
    source text NOT NULL DEFAULT '' CHECK (source IN ('', 'hook', 'meta', 'hook+meta')),
    created_at text NOT NULL
);
CREATE INDEX idx_memory_provenance_knowledge ON memory_provenance (knowledge_id);
CREATE INDEX idx_memory_provenance_session ON memory_provenance (session_id, created_at);

CREATE FUNCTION tam_memory_provenance_cascade() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    DELETE FROM memory_provenance WHERE knowledge_id = OLD.id;
    RETURN OLD;
END;
$$;
CREATE TRIGGER trg_memory_provenance_cascade AFTER DELETE ON knowledge
    FOR EACH ROW EXECUTE FUNCTION tam_memory_provenance_cascade();

