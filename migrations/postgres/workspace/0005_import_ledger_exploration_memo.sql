-- PostgreSQL twin of migrations/042_import_ledger_exploration_memo.sql: the
-- import ledger used by `tam import` and the exploration memo tables behind
-- memory_exploration_record / memory_exploration_recall. Same mapping rules
-- as 0001_baseline.sql (INTEGER -> bigint, TEXT -> text, BLOB -> bytea,
-- INTEGER PRIMARY KEY -> identity, no FOREIGN KEY clauses).

CREATE TABLE import_ledger (
    kind text NOT NULL,
    project text NOT NULL,
    content_hash text NOT NULL,
    knowledge_id bigint,
    source_ref text NOT NULL DEFAULT '',
    imported_at text NOT NULL,
    PRIMARY KEY (kind, project, content_hash)
);
CREATE INDEX idx_import_ledger_knowledge ON import_ledger (knowledge_id NULLS FIRST);

CREATE TABLE exploration_memos (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project text NOT NULL,
    question text NOT NULL,
    question_hash text NOT NULL,
    conclusion text NOT NULL,
    root text NOT NULL,
    question_vector bytea,
    vector_model text,
    created_at text NOT NULL,
    updated_at text NOT NULL,
    UNIQUE (project, question_hash)
);
CREATE INDEX idx_exploration_memos_project ON exploration_memos (project, updated_at DESC);

CREATE TABLE exploration_memo_files (
    memo_id bigint NOT NULL,
    path text NOT NULL,
    sha256 text NOT NULL,
    size bigint NOT NULL,
    PRIMARY KEY (memo_id, path)
);

